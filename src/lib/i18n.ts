export type Lang = 'fr' | 'ar' | 'en' | 'it' | 'ru';

export const RTL_LANGS: Record<Lang, boolean> = {
  fr: false,
  en: false,
  it: false,
  ru: false,
  ar: true,
};

// Système de tracking des clés i18n manquantes
if (typeof window !== 'undefined') {
  (window as any).__MISSING_I18N__ = (window as any).__MISSING_I18N__ || {};
}

export function t(lang: Lang, path: string, fallback?: string): string {
  const segs = path.split('.');
  let cur: any = translations[lang] || translations.fr;
  for (const s of segs) {
    cur = cur?.[s];
  }

  // Si la clé n'existe pas, on la track
  if (cur === undefined && typeof window !== 'undefined') {
    (window as any).__MISSING_I18N__[path] = true;
  }

  return (cur ?? fallback ?? path);
}

export function isRTL(lang: Lang): boolean {
  return RTL_LANGS[lang] === true;
}

