import assert from 'node:assert/strict';
import { createMiniappTestDatabase, testIds, asTestRole, testDossier, seedTestUsers, seedTestRequest } from './lib/miniappTestDatabase.mjs';

const db=await createMiniappTestDatabase();
await seedTestUsers(db);
const requestId=n=>`10000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const photo=n=>`https://assets.example.invalid/presentation-${n}.jpg`;
const scalar=async(sql,values=[]) => (await db.query(sql,values)).rows[0]?.result;
const prepare=async(id,dossier,version=0,business=null)=>scalar('select public.dalil_admin_registration_prepare($1,$2,$3,$4,$5) result',[id,version,business,dossier.email,dossier]);
const confirm=async(row,plan=row.requested_plan,amount=(plan==='artisan'?30:59),reference=`TEST-${row.id}`)=>scalar(
  'select public.dalil_admin_registration_confirm_payment($1,$2,$3,$4,$5,$6) result',
  [row.id,row.version,plan,amount,reference,receivedAt]);
const publish=async row=>scalar('select public.dalil_admin_registration_publish($1,$2) result',[row.id,row.version]);
const receivedAt=new Date(Date.now()-60000).toISOString();
let passed=0;
function check(name,value){assert.ok(value,name);passed++;console.log('PASS',name);}
async function rejects(name,fn,pattern){await assert.rejects(fn,pattern);passed++;console.log('PASS',name);}

const artisanDossier=testDossier('artisan',{photoUrls:Array.from({length:5},(_,i)=>photo(i+1))});
await seedTestRequest(db,requestId(1),artisanDossier);
await asTestRole(db,testIds.other);
await rejects('Ordinary professional cannot list admin dossiers',()=>scalar('select public.dalil_admin_registration_list() result'),/administrateur/);
await rejects('Ordinary professional cannot prepare another business',()=>prepare(requestId(1),artisanDossier),/administrateur/);
await rejects('Ordinary professional cannot self-promote in admins',()=>db.query("insert into public.admins(id,role) values($1,'admin')",[testIds.other]),/permission denied/);
await rejects('Ordinary professional cannot self-promote through profile role',()=>db.query("update public.profiles set role='admin' where id=$1",[testIds.other]),/rôle/);
await asTestRole(db,testIds.admin);
let artisan=await prepare(requestId(1),artisanDossier);
check('Preparing creates a persisted draft without payment or ownership',artisan.status==='draft'&&artisan.version===1&&artisan.confirmed_plan===null&&artisan.public_url===null&&artisan.account_status==='not_ready');
await rejects('Duplicate preparation cannot create a second business',()=>prepare(requestId(1),artisanDossier),/changé/);
await rejects('Publication is refused without confirmed payment',()=>publish(artisan),/virement/);
await rejects('Artisan sixth presentation photo is rejected',()=>prepare(requestId(1),{...artisanDossier,photoUrls:[...artisanDossier.photoUrls,photo(6)]},1),/5 photos/);
await asTestRole(db,null,'anon');
check('Draft is invisible to public catalogue queries',(await db.query('select id from public.entreprise where id=$1',[artisan.entreprise_id])).rows.length===0);
await asTestRole(db,testIds.owner);
check('Email match alone does not grant unpaid draft access',(await scalar('select public.dalil_claim_my_miniapps() result')).claimed.length===0);
await asTestRole(db,testIds.admin);
await rejects('Wrong payment amount cannot activate a plan',()=>confirm(artisan,'artisan',1),/montant attendu/);
await rejects('Missing bank reference cannot confirm payment',()=>confirm(artisan,'artisan',30,''),/référence/);
let paid=await confirm(artisan);
check('Verified transfer records the actual plan, amount and audit state',paid.status==='paid'&&paid.payment_amount===30&&paid.confirmed_plan==='artisan'&&paid.payment_confirmed_at&&paid.public_url===null);
let retried=await confirm(artisan);
check('Payment retry is idempotent',retried.version===paid.version&&retried.payment_confirmed_at===paid.payment_confirmed_at);
await rejects('Paid dossier cannot be silently changed',()=>prepare(paid.id,{...artisanDossier,logoChoice:'create'},paid.version),/figé/);
artisan=await publish(paid);
check('Publication returns real public and account URLs',artisan.status==='published'&&artisan.public_url.endsWith('/cv')&&artisan.account_url.endsWith('/compte')&&artisan.assets_ready===true);
check('Publication retry is idempotent',(await publish(paid)).version===artisan.version);
await asTestRole(db,null,'anon');
const publicArtisan=(await db.query('select * from public.entreprise where id=$1',[artisan.entreprise_id])).rows[0];
check('Public record contains all five presentation photos and chosen template',publicArtisan.image_url.split(',\n').length===5&&publicArtisan.modele_cv==='business'&&publicArtisan.palette_cv==='prestige');
await asTestRole(db,testIds.owner);
const claimed=await scalar('select public.dalil_claim_my_miniapps() result');
check('Verified purchaser receives only their own published mini-app',claimed.claimed.length===1&&claimed.claimed[0]===artisan.entreprise_id);
const rights=await scalar('select public.dalil_get_my_showcase_entitlements($1) result',[artisan.entreprise_id]);
check('Existing entitlement resolver gives Artisan 5/2/1/1/1 rights',rights.plan==='artisan'&&rights.photo_limit===5&&rights.social_limit===2&&rights.models.length===1&&rights.palettes.length===1&&rights.openings.length===1);
await asTestRole(db,testIds.other);
check('Other professional never claims the purchaser business',(await scalar('select public.dalil_claim_my_miniapps() result')).claimed.length===0);
await rejects('Other professional cannot read owner entitlements',()=>scalar('select public.dalil_get_my_showcase_entitlements($1) result',[artisan.entreprise_id]),/Accès refusé/);
check('Other professional cannot rewrite commercial plan directly',(await db.query("update public.entreprise set formule_commerciale='Premium — 59 TND' where id=$1 returning id",[artisan.entreprise_id])).rows.length===0);

const premiumDossier=testDossier('premium',{companyName:'Dossier Premium fictif',photoUrls:Array.from({length:10},(_,i)=>photo(i+1)),presentationModel:'portfolio',palette:'ivory',openingStyle:'framed'});
await seedTestRequest(db,requestId(2),premiumDossier);
await asTestRole(db,testIds.admin);
let premium=await prepare(requestId(2),premiumDossier);
await rejects('Premium eleventh presentation photo is rejected',()=>prepare(premium.id,{...premiumDossier,photoUrls:[...premiumDossier.photoUrls,photo(11)]},premium.version),/10 photos/);
premium=await publish(await confirm(premium));
await asTestRole(db,testIds.owner);
await scalar('select public.dalil_claim_my_miniapps() result');
const premiumRights=await scalar('select public.dalil_get_my_showcase_entitlements($1) result',[premium.entreprise_id]);
check('Premium ninth and tenth photos and 10/2/3/2 rights survive publication',premiumRights.photo_count===10&&premiumRights.photo_limit===10&&premiumRights.models.length===2&&premiumRights.palettes.length===3&&premiumRights.openings.length===2);
await db.exec('reset role');
await db.query("update public.entreprise set formule_commerciale='Artisan',statut_abonnement='Artisan',image_url='stale',modele_cv='business' where id=$1",[premium.entreprise_id]);
await asTestRole(db,testIds.owner);
const afterSync=await scalar('select public.dalil_get_my_showcase_entitlements($1) result',[premium.entreprise_id]);
check('Stale external sync cannot erase verified purchase, photos or model',afterSync.plan==='premium'&&afterSync.photo_count===10&&afterSync.current_model==='portfolio');

const logoDossier=testDossier('artisan',{companyName:'Dossier logo fictif',logoChoice:'create'});
await seedTestRequest(db,requestId(3),logoDossier);
await asTestRole(db,testIds.admin);
let logo=await prepare(requestId(3),logoDossier);
await rejects('Logo supplement cannot be omitted from confirmed amount',()=>confirm(logo,'artisan',30),/50 TND/);
logo=await confirm(logo,'artisan',50);
await rejects('Paid logo cannot be announced delivered without an image',()=>publish(logo),/logo/);
await rejects('Logo JavaScript URL is rejected',()=>scalar('select public.dalil_admin_registration_finish_assets($1,$2,$3) result',[logo.id,logo.version,'javascript:alert(1)']),/Lien invalide/);
logo=await scalar('select public.dalil_admin_registration_finish_assets($1,$2,$3) result',[logo.id,logo.version,'https://assets.example.invalid/logo.png']);
check('Delivered logo is persisted before publication',logo.assets_ready===true&&logo.reviewed_dossier.logoUrl==='https://assets.example.invalid/logo.png');
check('Complete paid logo dossier can publish',(await publish(logo)).status==='published');

await db.exec('reset role');
await db.query("insert into public.entreprise(id,nom,ville,categorie,telephone,a_propos,approved,statut_validation,statut_publication,slug,slug_court,formule_commerciale,statut_abonnement,image_url) values('legacy-test','Fiche historique fictive','Tunis',array['Artisanat'],'00000000','Texte historique',true,'publie','Publié','historique','historique','Premium — 59 TND','Premium',$1)",[Array.from({length:12},(_,i)=>photo(i+1)).join(',\n')]);
const legacyBefore=await scalar("select to_jsonb(e) result from public.entreprise e where id='legacy-test'");
await seedTestRequest(db,requestId(4),testDossier('artisan'));
await asTestRole(db,testIds.admin);
let legacy=await prepare(requestId(4),testDossier('artisan'),0,'legacy-test');
await rejects('Confirmed transfer cannot downgrade an existing Premium client',()=>confirm(legacy,'artisan',30),/droits acquis/);
await db.exec('reset role');
const legacyAfter=await scalar("select to_jsonb(e) result from public.entreprise e where id='legacy-test'");
check('Linking an existing establishment preserves all real content and URLs',JSON.stringify(legacyBefore)===JSON.stringify(legacyAfter));
await asTestRole(db,testIds.admin);
legacy=await confirm(legacy,'premium',59);
legacy=await publish(legacy);
await db.exec('reset role');
const existingRights=await scalar("select public.dalil_resolve_showcase_entitlements(e) result from public.entreprise e where id='legacy-test'");
check('Historical twelve-photo capacity survives confirmed purchase',existingRights.photo_limit===12);
const audit=await scalar('select count(*)::int result from public.dalil_miniapp_onboarding_events where suggestion_id=$1 and action=\'payment_confirmed\'',[artisan.id]);
check('Payment retries produce only one financial audit entry',audit===1);
await asTestRole(db,testIds.admin);
const list=await scalar('select public.dalil_admin_registration_list() result');
check('Admin list reports persisted state of each dossier',list.dossiers.length===4&&list.dossiers.find(x=>x.id===artisan.id).status==='active');
await db.close();
console.log(`PASS ${passed} PostgreSQL onboarding/payment/publication/security checks`);
